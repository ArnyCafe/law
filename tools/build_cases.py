def clean(t):
    t = re.sub(r'\s+', '', t)
    t = re.sub(r'[（(]?(?:參照)?(?:最高法院|勞動部|行政院勞工委員會|勞委會|內政部|前行政院勞工委員會)?[^，。；]*$', '', t) if False else t
    # drop trailing citation opener
    t = re.sub(r'[（(][^（()）]*$', '', t)
    t = re.sub(r'(此有|亦有|有|依|參照)?(勞動部|行政院勞工委員會|勞委會|改制前勞委會|內政部)[^，。；]*$', '', t)
    t = t.rstrip('，、；（( ')
    if t and t[-1] not in '。」':
        t += '。'
    return t

