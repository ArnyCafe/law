def cut(t, s, e):
    t = re.sub(r'\s+', '', t)  # 裁判書部分以固定寬度斷行
    i = t.find(s)
    assert i >= 0, ('start not found', s)
    j = t.find(e, i)
    assert j >= 0, ('end not found', e)
    return t[i:j + len(e)]


def tidy(x):
    x = re.sub(r'^[（(]?[一二三四五六七八九十]+[）)]|^[㈠-㈩]', '', x)
    x = re.sub(r'\s+', '', x)
    x = re.sub(r'^(?:次按|按|又|惟查，)', '', x)
    return x if x.endswith(('。', '；', '」')) else x + '。'


def cid(title):
    m = re.search(r'(\d+)年度?(\D+?)字第(\d+)號', title)
    return 'C' + (m.group(1) + m.group(2) + m.group(3) if m else hashlib.md5(title.encode()).hexdigest()[:8])


